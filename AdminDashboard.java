    private void btnSaveElectionStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveElectionStatusActionPerformed
       

String status = cmbElectionStatus.getSelectedItem().toString();

String updateSQL =
    "UPDATE election_settings "
  + "SET election_status = ? WHERE setting_id = 1";

try (java.sql.Connection con = DBConnection.connect()) {

    if (con == null) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Database connection failed."
        );
        return;
    }

    try (java.sql.PreparedStatement ps =
             con.prepareStatement(updateSQL)) {

        ps.setString(1, status);
        int rows = ps.executeUpdate();

        if (rows == 0) {
            String insertSQL =
                "INSERT INTO election_settings "
              + "(setting_id, election_status) VALUES (1, ?)";

            try (java.sql.PreparedStatement insert =
                     con.prepareStatement(insertSQL)) {
                insert.setString(1, status);
                insert.executeUpdate();
            }
        }
    }

    cmbElectionStatus.setSelectedItem(status);

    javax.swing.JOptionPane.showMessageDialog(
        this, "Election status saved: " + status
    );

} catch (java.sql.SQLException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Unable to save election status: " + e.getMessage()
    );
}


    }//GEN-LAST:event_btnSaveElectionStatusActionPerformed

