private void loadDashboardCounts() {
    try (java.sql.Connection con = DBConnection.connect()) {

        if (con == null) {
            lblRegisteredVoters.setText("0");
            lblVotesSubmitted.setText("0");
            lblTotalCandidates.setText("0");
            cmbElectionStatus.setSelectedItem("Not Started");
            return;
        }

        // Total registered voters
        String sqlUsers =
            "SELECT COUNT(*) FROM tbl_users WHERE role = 1";

        try (java.sql.PreparedStatement ps =
                 con.prepareStatement(sqlUsers);
             java.sql.ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {
                lblRegisteredVoters.setText(
                    String.valueOf(rs.getInt(1))
                );
            }
        }

        // Total votes submitted
        String sqlVotes = "SELECT COUNT(*) FROM votes";

        try (java.sql.PreparedStatement ps =
                 con.prepareStatement(sqlVotes);
             java.sql.ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {
                lblVotesSubmitted.setText(
                    String.valueOf(rs.getInt(1))
                );
            }
        }

        // Total candidates
        String sqlCandidates = "SELECT COUNT(*) FROM candidates";

        try (java.sql.PreparedStatement ps =
                 con.prepareStatement(sqlCandidates);
             java.sql.ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {
                lblTotalCandidates.setText(
                    String.valueOf(rs.getInt(1))
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to load dashboard counts: " + e.getMessage()
        );
    }
}


private void loadElectionStatus() {

    String sql = "SELECT election_status FROM election_settings "
               + "WHERE setting_id = 1";

    try (java.sql.Connection con = DBConnection.connect()) {

        if (con == null) {
            return;
        }

        try (java.sql.PreparedStatement ps = con.prepareStatement(sql);
             java.sql.ResultSet rs = ps.executeQuery()) {

            if (rs.next()) {
                cmbElectionStatus.setSelectedItem(
                    rs.getString("election_status")
                );
            }
        }

    } catch (java.sql.SQLException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Unable to load election status: " + e.getMessage()
        );
    }
}

