    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

        String studentID = Username.getText().trim();
        String pW = new String(password.getPassword());

        if (studentID.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your Student ID or username.");
            return;
        }

        if (pW.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter your password.");
            return;
        }

// ADMIN LOGIN
        if (studentID.equals("admin")) {

            if (pW.equals("admin123")) {

                try (Connection conn = DBConnection.connect()) {

                    if (conn == null) {
                        JOptionPane.showMessageDialog(this, "Cannot connect to the database.");
                        return;
                    }

                    String sql = "SELECT user_id FROM tbl_users WHERE student_id = ? AND role = 2";

                    try (PreparedStatement pst = conn.prepareStatement(sql)) {
                        pst.setString(1, "9999999999");

                        try (ResultSet rs = pst.executeQuery()) {

                            if (rs.next()) {
                                int userId = rs.getInt("user_id");

                                UserSession.setUser(userId, "admin");

                                JOptionPane.showMessageDialog(this, "Admin login successful!");

                                AdminDashboard dashboard = new AdminDashboard();
                                dashboard.setVisible(true);
                                this.dispose();

                            } else {
                                JOptionPane.showMessageDialog(
                                        this,
                                        "Admin account not found. Please create the admin account in the database."
                                );
                            }
                        }
                    }

                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Login error: " + e.getMessage());
                }

            } else {
                JOptionPane.showMessageDialog(this, "Invalid admin password.");
            }

            return;
        }

// STUDENT LOGIN: NUMBERS ONLY
        if (!studentID.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "Student ID must contain numbers only.");
            return;
        }

        Connection conn = DBConnection.connect();

        if (conn == null) {
            JOptionPane.showMessageDialog(this, "Cannot connect to the database.");
            return;
        }

        String sql = "SELECT * FROM tbl_users WHERE student_id = ? AND password = ?";

        try (conn;
                PreparedStatement pst = conn.prepareStatement(sql)) {

            pst.setString(1, studentID);
            pst.setString(2, pW);

            try (ResultSet rs = pst.executeQuery()) {

                if (rs.next()) {
                    int userId = rs.getInt("user_id");
                    int role = rs.getInt("role");

                    UserSession.setUser(userId, studentID);

                    JOptionPane.showMessageDialog(this, "Login successful!");

                    if (role == 2) {
                        AdminDashboard dashboard = new AdminDashboard();
                        dashboard.setVisible(true);
                    } else {
                        homie home = new homie();
                        home.setVisible(true);
                    }

                    this.dispose();

                } else {
                    JOptionPane.showMessageDialog(
                            this, "Invalid Student ID or password."
                    );
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this, "Login error: " + e.getMessage()
            );
        }


    }//GEN-LAST:event_jButton2ActionPerformed

